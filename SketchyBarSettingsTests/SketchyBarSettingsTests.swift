final class TemplateRendererTests: XCTestCase {
    func testRenderIncludesEnabledWidgets() throws {
        let input = RenderInput(
            bar: BarSettings(),
            widgets: WidgetConfig.defaults
        )
        let output = try TemplateRenderer.render(input)

        XCTAssertTrue(output.contains("sketchybar --add item date center"))
        XCTAssertTrue(output.contains("sketchybar --add item clock center"))
        XCTAssertTrue(output.contains("sketchybar --add item spotify center"))
        XCTAssertTrue(output.contains("sketchybar --add item spotify_cover center"))
        XCTAssertTrue(output.contains("sketchybar --add bracket spotify_group spotify_cover spotify"))
        let centerBracket = output.components(separatedBy: "sketchybar --add bracket center_status").dropFirst().first ?? ""
        XCTAssertTrue(centerBracket.contains("spotify_cover"))
        XCTAssertFalse(centerBracket.hasPrefix(" spotify_group") || centerBracket.contains(" center_status spotify_group"))
        XCTAssertFalse(output.contains("sketchybar --add bracket center_status") && centerBracket.split(separator: "\n").first?.contains("spotify_group") == true)
    }

    func testRenderOmitsDisabledWidgets() throws {
        var widgets = WidgetConfig.defaults
        widgets[0].enabled = false
        let input = RenderInput(bar: BarSettings(), widgets: widgets)
        let output = try TemplateRenderer.render(input)

        XCTAssertFalse(output.contains("sketchybar --add item date center"))
        XCTAssertTrue(output.contains("sketchybar --add item clock center"))
    }

    func testRenderRespectsPlacementAndOrder() throws {
        var widgets = WidgetConfig.defaults
        widgets = widgets.map { widget in
            var w = widget
            if w.id == "battery" {
                w.placement = .right
                w.order = 0
            }
            if w.id == "volume" {
                w.placement = .right
                w.order = 1
            }
            return w
        }

        let output = try TemplateRenderer.render(RenderInput(bar: BarSettings(), widgets: widgets))
        XCTAssertTrue(output.contains("sketchybar --add item battery right"))
        XCTAssertTrue(output.contains("sketchybar --add bracket status battery volume"))
    }

    func testRenderUsesBarSettings() throws {
        var bar = BarSettings()
        bar.height = 48
        bar.yOffset = 6
        bar.backgroundHex = "0xFF112233"
        bar.shadow = true

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        XCTAssertTrue(output.contains("height=48"))
        XCTAssertTrue(output.contains("y_offset=6"))
        XCTAssertTrue(output.contains("color=0xFF112233"))
        XCTAssertTrue(output.contains("shadow=on"))
    }

    func testRenderAppliesOpaqueBarBackgroundHex() throws {
        var bar = BarSettings()
        bar.backgroundHex = "0xFF336699"

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        XCTAssertTrue(output.contains("color=0xFF336699"))
    }

    func testRenderLoadsTemplateFromBundleAndAppliesBarValues() throws {
        var bar = BarSettings()
        bar.height = 52
        bar.yOffset = 8
        bar.backgroundHex = "0xFFABCDEF"

        let output = try TemplateRenderer.render(
            RenderInput(bar: bar, widgets: WidgetConfig.defaults)
        )

        XCTAssertTrue(output.contains("height=52"))
        XCTAssertTrue(output.contains("y_offset=8"))
        XCTAssertTrue(output.contains("color=0xFFABCDEF"))
        XCTAssertTrue(output.contains("# Generated by SketchyBar Settings. DO NOT EDIT BY HAND."))
    }

    func testRenderAppliesValuesFromCustomTemplate() throws {
        let loader = StringTemplateLoader(template: """
        BAR={{BAR_HEIGHT}}
        SHADOW={{BAR_SHADOW}}
        {{WIDGET_BLOCKS}}
        """)

        var bar = BarSettings()
        bar.height = 44
        bar.shadow = true

        let output = try TemplateRenderer.render(
            RenderInput(bar: bar, widgets: []),
            loader: loader
        )

        XCTAssertEqual(output, "BAR=44\nSHADOW=on\n")
    }

    func testRenderFailsWhenTemplateMissing() {
        struct MissingTemplateLoader: TemplateLoading {
            func loadTemplate(named name: String) throws -> String {
                throw TemplateRenderError.templateNotFound(name)
            }
        }

        XCTAssertThrowsError(
            try TemplateRenderer.render(RenderInput(bar: BarSettings(), widgets: []), loader: MissingTemplateLoader())
        ) { error in
            XCTAssertEqual(error as? TemplateRenderError, .templateNotFound("sketchybarrc.template"))
        }
    }
}

final class SettingsStoreTests: XCTestCase {
    private var suiteName = ""
    private var defaults: UserDefaults!
    private var store: SettingsStore!

    override func setUp() {
        super.setUp()
        suiteName = "SketchyBarSettingsTests.\(UUID().uuidString)"
        defaults = UserDefaults(suiteName: suiteName)!
        store = SettingsStore(
            defaults: defaults,
            defaultsKey: "test.settings",
            configPath: "/tmp/sketchybar-test/sketchybarrc",
            pluginsDir: "/tmp/sketchybar-test/plugins"
        )
    }

    override func tearDown() {
        defaults.removePersistentDomain(forName: suiteName)
        store = nil
        defaults = nil
        super.tearDown()
    }

    func testTogglePersists() {
        let id = "date"
        let initial = store.widget(id: id)?.enabled ?? true
        store.toggle(id)

        let reloaded = SettingsStore(
            defaults: defaults,
            defaultsKey: "test.settings",
            configPath: "/tmp/sketchybar-test/sketchybarrc",
            pluginsDir: "/tmp/sketchybar-test/plugins"
        )

        XCTAssertEqual(reloaded.widget(id: id)?.enabled, !initial)
    }

    private func keepOnlyEnabled(ids: [String]) {
        for widget in store.widgets {
            let shouldEnable = ids.contains(widget.id)
            if widget.enabled != shouldEnable {
                store.toggle(widget.id)
            }
        }
        for id in ids {
            store.setPlacement(id, .center)
        }
    }

    func testMoveChangesOrderWithinPlacement() {
        keepOnlyEnabled(ids: ["date", "clock"])

        let before = store.widgets(in: .center).map(\.id)
        store.move("clock", up: true)
        let after = store.widgets(in: .center).map(\.id)

        XCTAssertNotEqual(before, after)
        XCTAssertEqual(after.first, "clock")
    }

    func testSetPlacementAppendsToEnd() {
        store.setPlacement("date", .center)
        store.setPlacement("clock", .center)
        store.setPlacement("battery", .right)

        store.setPlacement("date", .right)

        let rightOrder = store.widgets(in: .right).map(\.id)
        XCTAssertEqual(rightOrder.last, "date")
    }

    func testReorderWidgetMovesWithinPlacement() {
        keepOnlyEnabled(ids: ["date", "clock", "ai_usage"])

        store.reorderWidget(id: "ai_usage", toIndex: 0, in: .center)

        XCTAssertEqual(store.widgets(in: .center).map(\.id).first, "ai_usage")
    }

    func testMoveWidgetBeforeInsertsAtTarget() {
        keepOnlyEnabled(ids: ["date", "clock", "ai_usage"])

        store.moveWidgetBefore("ai_usage", targetID: "clock")

        XCTAssertEqual(store.widgets(in: .center).map(\.id), ["date", "ai_usage", "clock"])
    }

    func testMoveWidgetBeforeIgnoresDifferentPlacement() {
        store.setPlacement("date", .center)
        store.setPlacement("battery", .right)

        let beforeDate = store.widget(id: "date")?.placement
        store.moveWidgetBefore("date", targetID: "battery")

        XCTAssertEqual(store.widget(id: "date")?.placement, beforeDate)
    }

    func testResetToDefaults() {
        store.bar.height = 99
        store.toggle("date")
        store.resetToDefaults()

        XCTAssertEqual(store.bar.height, BarSettings().height)
        XCTAssertTrue(store.widget(id: "date")?.enabled ?? false)
    }

    func testUpdateBarBackgroundHexPersists() {
        store.updateBarBackgroundHex("0xFFC97C5D")

