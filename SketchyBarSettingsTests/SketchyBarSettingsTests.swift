final class SketchyBarColorHexTests: XCTestCase {
    func testParseValidARGB() {
        let components = SketchyBarColorHex.parse("0xFF112233")
        XCTAssertEqual(components?.a, 255)
        XCTAssertEqual(components?.r, 0x11)
        XCTAssertEqual(components?.g, 0x22)
        XCTAssertEqual(components?.b, 0x33)
    }

    func testParseValidRGBAssumesOpaqueAlpha() {
        let components = SketchyBarColorHex.parse("0x112233")
        XCTAssertEqual(components?.a, 255)
        XCTAssertEqual(components?.r, 0x11)
    }

    func testParseTransparentAlpha() {
        let components = SketchyBarColorHex.parse("0x80112233")
        XCTAssertEqual(components?.a, 0x80)
    }

    func testSanitizedRejectsInvalidHex() {
        XCTAssertEqual(
            SketchyBarColorHex.sanitized("not-a-color", fallback: "0x00000000"),
            "0x00000000"
        )
    }

    func testFormatRoundTrip() {
        let formatted = SketchyBarColorHex.format((a: 128, r: 1, g: 2, b: 3))
        XCTAssertEqual(formatted, "0x80010203")
        XCTAssertEqual(SketchyBarColorHex.parse(formatted)?.a, 128)
    }

    func testHexFromColorPreservesARGB() {
        let color = Color(
            .sRGB,
            red: 51.0 / 255.0,
            green: 102.0 / 255.0,
            blue: 153.0 / 255.0,
            opacity: 1.0
        )
        XCTAssertEqual(SketchyBarColorHex.hex(from: color), "0xFF336699")
    }

    func testColorFromHexPreservesAlpha() {
        let color = SketchyBarColorHex.color(from: "0x80336699")
        XCTAssertEqual(SketchyBarColorHex.hex(from: color), "0x80336699")
    }
}

final class TemplateRendererStyleTests: XCTestCase {
    func testRenderUsesCustomFontFamily() throws {
        var bar = BarSettings()
        bar.fontFamily = "Helvetica Neue"
        bar.fontSize = 15

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        XCTAssertTrue(output.contains("label.font=\"Helvetica Neue:Medium:15.0\""))
    }

    func testRenderUsesGlobalFontForAllWidgets() throws {
        var bar = BarSettings()
        bar.fontFamily = "SF Pro Text"
        bar.fontSize = 13

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        XCTAssertTrue(output.contains("label.font=\"SF Pro Text:Medium:13.0\""))
    }

    func testRenderIgnoresLegacyWidgetFontFamily() throws {
        var bar = BarSettings()
        bar.fontFamily = "SF Pro Text"
        bar.fontSize = 13

        var widgets = WidgetConfig.defaults
        if let index = widgets.firstIndex(where: { $0.id == "date" }) {
            widgets[index].fontFamily = "UDEV Gothic 35JPDOC"
            widgets[index].fontSize = 20
        }

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: widgets))
        let expectedFont = "SF Pro Text:Medium:13.0"
        let dateBlock = itemBlock(in: output, id: "date")

        XCTAssertTrue(dateBlock.contains("label.font=\"\(expectedFont)\""))
        XCTAssertTrue(dateBlock.contains("icon.font=\"\(expectedFont)\""))
        XCTAssertFalse(output.contains("UDEV Gothic"))
        XCTAssertFalse(output.contains(":20.0"))

        let itemIDs = ["date", "clock", "ai_usage", "volume", "audio_output", "spotify_cover", "spotify"]
        for id in itemIDs {
            let block = itemBlock(in: output, id: id)
            XCTAssertTrue(block.contains("label.font=\"\(expectedFont)\""), id)
            XCTAssertTrue(block.contains("icon.font=\"\(expectedFont)\""), id)
        }

        let layout = ResolvedBarLayout.make(from: RenderInput(bar: bar, widgets: widgets))
        XCTAssertEqual(layout.fontFamily, "SF Pro Text")
        XCTAssertEqual(layout.fontSize, 13)
        XCTAssertEqual(Set(layout.allWidgets.map(\.fontFamily)), ["SF Pro Text"])
        XCTAssertEqual(Set(layout.allWidgets.map(\.fontSize)), [13])
    }

    private func itemBlock(in output: String, id: String) -> String {
        let marker = "sketchybar --add item \(id) "
        guard let start = output.range(of: marker) else { return "" }
        let fromStart = output[start.lowerBound...]
        let afterMarker = fromStart.dropFirst(marker.count)
        if let next = afterMarker.range(of: "\nsketchybar --add ") {
            return String(fromStart[..<next.lowerBound])
        }
        return String(fromStart)
    }

    func testRenderAppliesGlobalWidgetPadding() throws {
        var bar = BarSettings()
        bar.widgetPadding = 8

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        let dateBlock = output.components(separatedBy: "sketchybar --add item date center").dropFirst().first ?? ""
        XCTAssertTrue(dateBlock.contains("label.padding_left=8"))
        XCTAssertTrue(dateBlock.contains("label.padding_right=8"))
        XCTAssertFalse(dateBlock.contains("background.padding_left"))
        XCTAssertFalse(dateBlock.contains("background.padding_right"))
    }

    func testRenderItemSpacingDoesNotDoubleWithWidgetPadding() throws {
        var bar = BarSettings()
        bar.widgetPadding = 4
        bar.itemSpacing = 8

        var widgets = WidgetConfig.defaults
        widgets = widgets.filter { $0.id == "date" || $0.id == "clock" }
        for index in widgets.indices {
            widgets[index].backgroundEnabled = true
        }

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: widgets))
        let dateBlock = output.components(separatedBy: "sketchybar --add item date center").dropFirst().first ?? ""
        let clockBlock = output.components(separatedBy: "sketchybar --add item clock center").dropFirst().first ?? ""

        XCTAssertTrue(dateBlock.contains("padding_left=0"))
        XCTAssertTrue(dateBlock.contains("padding_right=8"))
        XCTAssertTrue(dateBlock.contains("label.padding_left=4"))
        XCTAssertTrue(dateBlock.contains("label.padding_right=4"))
        XCTAssertFalse(dateBlock.contains("background.padding_left"))
        XCTAssertTrue(clockBlock.contains("padding_left=0"))
        XCTAssertTrue(clockBlock.contains("padding_right=0"))
        XCTAssertTrue(clockBlock.contains("label.padding_left=4"))

        let dateOuter = ItemLayoutMetrics.outerPadding(itemSpacing: 8, isFirst: true, isLast: false)
        let clockOuter = ItemLayoutMetrics.outerPadding(itemSpacing: 8, isFirst: false, isLast: true)
        XCTAssertEqual(ItemLayoutMetrics.gapBetweenCards(leftOuter: dateOuter, rightOuter: clockOuter), 8)
    }

    func testRenderAppliesWhiteColor() throws {
        var widgets = WidgetConfig.defaults
        if let index = widgets.firstIndex(where: { $0.id == "clock" }) {
            widgets[index].colorHex = EarthColorCatalog.white
        }

        let output = try TemplateRenderer.render(RenderInput(bar: BarSettings(), widgets: widgets))
        let block = output.components(separatedBy: "sketchybar --add item clock center").dropFirst().first ?? ""
        XCTAssertTrue(block.contains("label.color=\"0xFFFFFFFF\""))
        XCTAssertTrue(block.contains("icon.color=\"0xFFFFFFFF\""))
    }

    func testRenderSpotifyGroupPaddingAndBracket() throws {
        var bar = BarSettings()
        bar.widgetPadding = 6
        bar.itemSpacing = 10

        let output = try TemplateRenderer.render(RenderInput(bar: bar, widgets: WidgetConfig.defaults))
        let coverBlock = output.components(separatedBy: "sketchybar --add item spotify_cover").dropFirst().first ?? ""
        let spotifyBlock = output.components(separatedBy: "sketchybar --add item spotify center").dropFirst().first ?? ""
        let groupBlock = output.components(separatedBy: "sketchybar --add bracket spotify_group").dropFirst().first ?? ""

        XCTAssertTrue(coverBlock.contains("padding_left=6"))
        XCTAssertTrue(coverBlock.contains("padding_right=0"))
        XCTAssertTrue(coverBlock.contains("background.drawing=on"))
        XCTAssertTrue(coverBlock.contains("background.color=\"0x00000000\""))
        XCTAssertTrue(spotifyBlock.contains("label.padding_right=6"))
        XCTAssertTrue(spotifyBlock.contains("padding_right=0"))
